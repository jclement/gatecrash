package main

import (
	"crypto/ed25519"
	"crypto/rand"
	"encoding/base64"
	"encoding/pem"
	"fmt"
	"os"

	"golang.org/x/crypto/bcrypt"
	gossh "golang.org/x/crypto/ssh"
)

// Bootstraps the local dev environment used by the `server`, `server:auth`, and
// `client` mise tasks. It generates (idempotently) a stable SSH host key, a dev
// tunnel secret, and writes:
//
//	.dev/host_key        — server SSH host key (stable across restarts)
//	.dev/gatecrash.toml  — dev server config (plain HTTP :21443, SSH :21022)
//	.dev/client.env      — connection details sourced by the `client` task
//
// If .dev/gatecrash.toml already exists it does nothing, so the host key,
// session secret, and tunnel secret stay stable. Re-run after `mise run clean`.
func main() {
	const (
		configPath = ".dev/gatecrash.toml"
		hostKey    = ".dev/host_key"
		clientEnv  = ".dev/client.env"
		sshPort    = 21022
		httpsPort  = 21443
		adminHost  = "gatecrash.lvh.me"
		tunnelHost = "app.lvh.me"
		tunnelID   = "dev"
	)

	if _, err := os.Stat(configPath); err == nil {
		fmt.Println("dev config already exists, leaving it untouched:", configPath)
		return
	}

	// Stable SSH host key.
	_, priv, err := ed25519.GenerateKey(rand.Reader)
	if err != nil {
		panic(err)
	}
	pemBlock, err := gossh.MarshalPrivateKey(priv, "gatecrash dev host key")
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(hostKey, pem.EncodeToMemory(pemBlock), 0o600); err != nil {
		panic(err)
	}
	signer, err := gossh.NewSignerFromKey(priv)
	if err != nil {
		panic(err)
	}
	fingerprint := gossh.FingerprintSHA256(signer.PublicKey())

	// Dev tunnel secret + its bcrypt hash for the server config.
	tunnelSecret := randToken()
	hash, err := bcrypt.GenerateFromPassword([]byte(tunnelSecret), 12)
	if err != nil {
		panic(err)
	}

	// Session signing secret.
	sessionSecret := randToken()

	config := fmt.Sprintf(`# Gatecrash LOCAL DEV config — generated by `+"`mise run dev:gen`"+`.
# Self-signed TLS on lvh.me hostnames (which resolve to 127.0.0.1).
# Admin panel: https://%s:%d  — do not use outside local development.

[server]
secret = %q
ssh_port = %d
https_port = %d
http_port = 0
bind_addr = "127.0.0.1"
admin_host = %q

[tls]
cert_dir = "./certs"

[update]
enabled = false
check_interval = "6h"
github_repo = "jclement/gatecrash"

[[tunnel]]
id = %q
type = "http"
hostnames = [%q]
secret_hash = %q
`, adminHost, httpsPort, sessionSecret, sshPort, httpsPort, adminHost, tunnelID, tunnelHost, hash)

	if err := os.WriteFile(configPath, []byte(config), 0o600); err != nil {
		panic(err)
	}

	env := fmt.Sprintf("DEV_SERVER=127.0.0.1:%d\nDEV_TOKEN=%s:%s\nDEV_HOST_KEY=%s\n",
		sshPort, tunnelID, tunnelSecret, fingerprint)
	if err := os.WriteFile(clientEnv, []byte(env), 0o600); err != nil {
		panic(err)
	}

	fmt.Println("Generated dev environment:")
	fmt.Println("  config:     ", configPath)
	fmt.Println("  host key:   ", hostKey)
	fmt.Println("  client env: ", clientEnv)
	fmt.Println("  fingerprint:", fingerprint)
	fmt.Printf("  admin:       https://%s:%d\n", adminHost, httpsPort)
}

func randToken() string {
	b := make([]byte, 24)
	if _, err := rand.Read(b); err != nil {
		panic(err)
	}
	return base64.RawURLEncoding.EncodeToString(b)
}
